"""Generate crates/mc-bot/src/state_table.rs from the vanilla data generator's blocks report.

usage: python -I tools/gen_state_table.py path/to/reports/blocks.json
Provenance: blocks.json is produced by running the official 1.21.1 server jar's data generator
(`--reports`). Only block names, property names/values and numeric ids are copied (facts needed
to speak the protocol); no Mojang code is read or included.
"""
import json
import sys
from pathlib import Path


def main():
    report = json.load(open(sys.argv[1], encoding="utf-8"))
    blocks = sorted(report.items(), key=lambda kv: min(s["id"] for s in kv[1]["states"]))
    props, rows, next_id = {}, [], 0
    for name, info in blocks:
        states = sorted(info["states"], key=lambda s: s["id"])
        ids = [s["id"] for s in states]
        names = list(info.get("properties", {}))
        # the report's key order is not always the id order: recover it from the strides
        stride = {p: next(i for i, s in enumerate(states) if s["properties"][p] != states[0]["properties"][p]) for p in names}
        names.sort(key=lambda p: -stride[p])
        values = [list(dict.fromkeys(s["properties"][p] for s in states)) for p in names]
        base = ids[0]
        assert base == next_id and ids == list(range(base, base + len(ids))), name
        # verify the mixed-radix layout (last property varies fastest)
        for s in info["states"]:
            off = 0
            for p, vals in zip(names, values):
                off = off * len(vals) + vals.index(s["properties"][p])
            assert base + off == s["id"], (name, s)
        default = next(s["id"] for s in info["states"] if s.get("default")) - base
        refs = [props.setdefault((p, ",".join(v)), len(props)) for p, v in zip(names, values)]
        rows.append((name.removeprefix("minecraft:"), base, default, refs))
        next_id = base + len(ids)
    out = ["// @generated by tools/gen_state_table.py from the 1.21.1 data generator report",
           "// reports/blocks.json (names, property values and numeric ids only). Do not edit.",
           "", "/// Total number of block states.", f"pub const STATE_COUNT: u32 = {next_id};",
           "", "/// Distinct properties: (name, comma separated values in id order).",
           "#[rustfmt::skip]", "pub const PROPS: &[(&str, &str)] = &["]
    out += [f'    ("{p}", "{v}"),' for p, v in props]
    out += ["];", "", "/// (block name, first state id, default offset, indices into PROPS), ascending by id.",
            "#[rustfmt::skip]", "pub const BLOCKS: &[(&str, u32, u16, &[u8])] = &["]
    out += [f'    ("{n}", {b}, {d}, &[{", ".join(map(str, r))}]),' for n, b, d, r in rows]
    out.append("];")
    assert len(props) < 256
    path = Path(__file__).resolve().parents[1] / "crates/mc-bot/src/state_table.rs"
    path.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(rows)} blocks, {len(props)} properties, {next_id} states -> {path}")


if __name__ == "__main__":
    main()
